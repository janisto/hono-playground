import { existsSync, readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import Ajv from "ajv";
import addFormats from "ajv-formats";
import { parse, printParseErrorCode } from "jsonc-parser";

const repositoryRoot = fileURLToPath(new URL("..", import.meta.url));
const configPath = path.join(repositoryRoot, "wrangler.jsonc");
const schemaPath = path.join(repositoryRoot, "node_modules/wrangler/config-schema.json");
const publicPath = path.join(repositoryRoot, "public");
const failures = [];

function check(condition, message) {
  if (!condition) {
    failures.push(message);
  }
}

function readJson(filePath, label) {
  try {
    return JSON.parse(readFileSync(filePath, "utf8"));
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new Error(
      `Unable to read ${label} at ${path.relative(repositoryRoot, filePath)}: ${reason}`,
    );
  }
}

function findPublicHtml(directory, relativeDirectory = "public") {
  if (!existsSync(directory)) {
    failures.push("public/ must exist because it is the configured Static Assets directory");
    return;
  }

  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const absolutePath = path.join(directory, entry.name);
    const relativePath = path.join(relativeDirectory, entry.name);

    if (entry.isDirectory()) {
      findPublicHtml(absolutePath, relativePath);
    } else if (entry.name.toLowerCase().endsWith(".html")) {
      failures.push(
        `${relativePath} is a public HTML asset; API/docs HTML must be generated by the Worker`,
      );
    }
  }
}

const parseErrors = [];
const source = readFileSync(configPath, "utf8");
const config = parse(source, parseErrors, {
  allowTrailingComma: true,
  disallowComments: false,
});

if (parseErrors.length > 0) {
  for (const error of parseErrors) {
    failures.push(
      `wrangler.jsonc parse error at offset ${error.offset}: ${printParseErrorCode(error.error)}`,
    );
  }
}

check(
  config !== null && typeof config === "object" && !Array.isArray(config),
  "config must be an object",
);

if (!existsSync(schemaPath)) {
  failures.push("Wrangler schema is missing; run pnpm install --frozen-lockfile first");
} else if (config !== null && typeof config === "object" && !Array.isArray(config)) {
  const schema = readJson(schemaPath, "the pinned Wrangler schema");
  const ajv = new Ajv({ allErrors: true, strict: false });
  addFormats(ajv);
  const validate = ajv.compile(schema);

  if (!validate(config)) {
    for (const error of validate.errors ?? []) {
      failures.push(
        `Wrangler schema ${error.instancePath || "/"} ${error.message ?? "validation failed"}`,
      );
    }
  }

  check(
    config.$schema === "./node_modules/wrangler/config-schema.json",
    "$schema must point to the pinned project-local Wrangler schema",
  );
  check(config.name === "hono-playground", "Worker name must remain hono-playground");
  check(config.main === "src/index.ts", "Worker entrypoint must remain src/index.ts");
  check(
    config.compatibility_date === "2026-07-22",
    "compatibility_date is a reviewed runtime pin and must remain 2026-07-22",
  );
  const environment = config.vars?.ENVIRONMENT;
  const deploymentProfile = config.vars?.DEPLOYMENT_PROFILE;
  check(
    environment === "development" || environment === "production",
    "ENVIRONMENT must be development or production in the deployable config",
  );
  check(
    deploymentProfile === "workers-dev-demo" || deploymentProfile === "custom-domain-production",
    "DEPLOYMENT_PROFILE must select a supported topology",
  );
  if (deploymentProfile === "workers-dev-demo") {
    check(config.workers_dev === true, "workers-dev-demo requires workers_dev: true");
    check(!Object.hasOwn(config, "routes"), "workers-dev-demo must not declare routes");
  }
  if (deploymentProfile === "custom-domain-production") {
    check(config.workers_dev === false, "custom-domain-production requires workers_dev: false");
    check(
      Array.isArray(config.routes) && config.routes.length > 0,
      "custom-domain-production requires a reviewed route",
    );
  }
  check(config.preview_urls === false, "preview_urls must be explicitly disabled");
  check(config.send_metrics === false, "send_metrics must be explicitly false");
  check(
    config.dependencies_instrumentation?.enabled === true,
    "dependencies_instrumentation.enabled must be explicitly true",
  );
  check(config.upload_source_maps === true, "upload_source_maps must be explicitly true");
  check(
    !Object.hasOwn(config, "limits") || !Object.hasOwn(config.limits ?? {}, "cpu_ms"),
    "the Free deployment must not declare the paid-only limits.cpu_ms setting",
  );

  const configurations = [
    ["top level", config],
    ...Object.entries(config.env ?? {}).map(([name, value]) => [`env.${name}`, value]),
  ];
  for (const [label, candidate] of configurations) {
    const flags = Array.isArray(candidate?.compatibility_flags)
      ? candidate.compatibility_flags
      : [];
    check(
      !flags.some((flag) => typeof flag === "string" && flag.includes("nodejs_compat")),
      `${label} must not enable a nodejs_compat compatibility flag`,
    );
  }

  check(config.assets?.directory === "./public", "assets.directory must be ./public");
  check(
    config.assets?.run_worker_first === false,
    "assets.run_worker_first must be explicitly false",
  );
  check(config.assets?.html_handling === "none", "assets.html_handling must be none");
  check(config.assets?.not_found_handling === "none", "assets.not_found_handling must be none");
  check(
    !Object.hasOwn(config.assets ?? {}, "binding"),
    "do not add an unused runtime asset binding",
  );

  check(config.observability?.enabled === true, "observability.enabled must be true");
  check(config.observability?.logs?.enabled === true, "observability.logs.enabled must be true");
  check(
    config.observability?.logs?.invocation_logs === true,
    "observability.logs.invocation_logs must be true",
  );
  check(
    config.observability?.logs?.head_sampling_rate === 1,
    "observability.logs.head_sampling_rate must remain the explicit Phase 7 value 1",
  );
  check(
    config.observability?.logs?.persist === true,
    "observability.logs.persist must be explicitly true",
  );
  check(
    !Object.hasOwn(config.observability?.logs ?? {}, "destinations"),
    "Phase 7 does not configure an external log destination",
  );
  check(
    config.observability?.traces?.enabled === true,
    "observability.traces.enabled must be true",
  );
  check(
    config.observability?.traces?.head_sampling_rate === 1,
    "observability.traces.head_sampling_rate must remain the explicit Phase 7 value 1",
  );
  check(
    config.observability?.traces?.persist === true,
    "observability.traces.persist must be explicitly true",
  );
  check(
    !Object.hasOwn(config.observability?.traces ?? {}, "destinations"),
    "Phase 7 does not configure an external trace destination",
  );

  check(
    config.version_metadata?.binding === "CF_VERSION_METADATA",
    "version_metadata.binding must remain CF_VERSION_METADATA",
  );
  check(!Object.hasOwn(config, "rate_limits"), "use Wrangler's ratelimits key, not rate_limits");

  const expectedRateLimits = new Map([
    ["PUBLIC_RATE_LIMITER", { localNamespaceId: "1001", limit: 300 }],
    ["PROFILE_READ_RATE_LIMITER", { localNamespaceId: "1002", limit: 120 }],
    ["PROFILE_WRITE_RATE_LIMITER", { localNamespaceId: "1003", limit: 30 }],
  ]);
  const rateLimits = Array.isArray(config.ratelimits) ? config.ratelimits : [];
  check(
    rateLimits.length === expectedRateLimits.size,
    "exactly three rate-limit bindings are required",
  );

  const seenBindings = new Set();
  const seenNamespaces = new Set();
  for (const rateLimit of rateLimits) {
    const expected = expectedRateLimits.get(rateLimit?.name);
    check(expected !== undefined, `unexpected rate-limit binding ${String(rateLimit?.name)}`);
    check(
      !seenBindings.has(rateLimit?.name),
      `duplicate rate-limit binding ${String(rateLimit?.name)}`,
    );
    seenBindings.add(rateLimit?.name);

    check(
      typeof rateLimit?.namespace_id === "string" && /^[1-9][0-9]*$/.test(rateLimit.namespace_id),
      `${String(rateLimit?.name)} namespace_id must be a positive-integer string`,
    );
    check(
      !seenNamespaces.has(rateLimit?.namespace_id),
      `${String(rateLimit?.name)} must use a unique namespace_id`,
    );
    seenNamespaces.add(rateLimit?.namespace_id);

    if (expected !== undefined) {
      if (environment === "production") {
        check(
          rateLimit.namespace_id !== expected.localNamespaceId,
          `${rateLimit.name}.namespace_id must use a reviewed production value, not reserved local ID ${expected.localNamespaceId}`,
        );
      } else {
        check(
          rateLimit.namespace_id === expected.localNamespaceId,
          `${rateLimit.name}.namespace_id must be reserved local ID ${expected.localNamespaceId} before production configuration`,
        );
      }
      check(
        rateLimit.simple?.limit === expected.limit,
        `${rateLimit.name}.simple.limit must be ${expected.limit}`,
      );
    }
    check(rateLimit?.simple?.period === 60, `${String(rateLimit?.name)}.simple.period must be 60`);
  }

  for (const binding of expectedRateLimits.keys()) {
    check(seenBindings.has(binding), `missing required rate-limit binding ${binding}`);
  }

  const databases = Array.isArray(config.d1_databases) ? config.d1_databases : [];
  check(databases.length === 1, "exactly one D1 binding is required");
  const database = databases[0];
  check(database?.binding === "DB", "D1 binding must remain DB");
  check(
    database?.database_name === "hono-playground",
    "D1 database_name must remain hono-playground",
  );
  check(database?.migrations_dir === "./migrations", "D1 migrations_dir must remain ./migrations");
  check(
    database?.remote !== true,
    "D1 remote mode must remain absent or false for local execution",
  );
  if (environment === "production") {
    check(
      typeof database?.database_id === "string" &&
        /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/iu.test(
          database.database_id,
        ),
      "production DB must use a live UUID database_id",
    );
  } else {
    check(
      !Object.hasOwn(database ?? {}, "database_id"),
      "development config must not invent a database_id before Phase 8 readback",
    );
  }
}

findPublicHtml(publicPath);

if (failures.length > 0) {
  console.error("Wrangler configuration check failed:");
  for (const failure of failures) {
    console.error(`- ${failure}`);
  }
  process.exitCode = 1;
} else {
  console.log("Wrangler schema, reviewed literals, and public asset tree are valid.");
}
